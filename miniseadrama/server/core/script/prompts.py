def _system(skill: str, stage_note: str) -> str:
    return (
        f"{skill.strip()}\n\n"
        "=====\n"
        f"{stage_note}\n"
        "只输出任务要求的内容，不要解释你的工作过程，不要加 Markdown 代码块围栏。\n"
        "成稿必须是干净的剧本文本：禁止出现任何“AI 生成”“由人工智能创作”“Generated by AI”"
        "之类的声明、水印、署名、免责声明或页脚。"
    )


def build_plan_messages(skill: str, transcript: str) -> List[Dict[str, str]]:
    stage_note = (
        "【当前阶段：策划】\n"
        "你要完成第①步到第④步：提炼剧本 DNA、自己选定改编方向、写全剧大钩子、"
        "出分集大纲（40~60 集），并给出情节类别、剧情梗概、封面设计说明。"
        "人物台词设定卡在下一阶段单独生成，本阶段不要输出。\n"
        "严格按照下面的 JSON 结构输出，字段一个都不能少，episodes 必须覆盖全剧每一集。\n"
        "硬性约束：所有字符串值必须写在同一行内，不得包含换行；"
        "需要引用时用「」，不要用英文双引号；每段文字尽量简短。\n"
        "字数硬性限制：logline 是最多 40 个字的一句话卖点，必须完整成句、不得超字；"
        "plot_summary 三段合并后不超过 300 个字，宁可少写也不能超。\n"
        f"{PLAN_SCHEMA}"
    )
    user = (
        "下面是原作全剧字幕稿（含集号）。请按系统提示词的要求完成策划阶段。\n\n"
        "【原作字幕稿】\n"
        f"{transcript}"
    )
    return [
        {"role": "system", "content": _system(skill, stage_note)},
        {"role": "user", "content": user},
    ]


def build_character_messages(skill: str, plan: Dict[str, Any]) -> List[Dict[str, str]]:
    stage_note = (
        "【当前阶段：人物台词设定卡】\n"
        "根据已经定稿的大纲，为主角、反派、贯穿全剧的配角各写一张 13 行人物卡。"
        "每人必须齐三样：一根筋、反差、招牌（英文句＋动作或道具），并给出一行外形锁定。"
        "严格按下面的 JSON 结构输出：\n"
        f"{CHARACTER_SCHEMA}"
    )
    user = (
        f"剧名：{plan.get('title_en')}\n"
        f"大钩子：{plan.get('logline')}\n\n"
        f"【剧情梗概】\n" + "\n".join(plan.get("plot_summary") or []) + "\n\n"
        f"【分集大纲】\n{_compact_outline(plan)}\n\n"
        "请输出全剧主要人物的人物台词设定卡。"
    )
    return [
        {"role": "system", "content": _system(skill, stage_note)},
        {"role": "user", "content": user},
    ]


def _compact_outline(plan: Dict[str, Any]) -> str:
    lines: List[str] = []
    for episode in plan.get("episodes", []):
        scenes = "；".join(str(item) for item in episode.get("scenes", []))
        lines.append(
            f"第 {episode.get('number')} 集｜事件：{episode.get('event', '')}"
            f"｜情绪：{episode.get('emotion', '')}"
            f"｜场次：{scenes}"
            f"｜钩子：{episode.get('hook', '')}"
        )
    return "\n".join(lines)


def _characters_digest(plan: Dict[str, Any]) -> str:
    lines: List[str] = []
    for item in plan.get("characters", []):
        lines.append(
            f"{item.get('name')}（{item.get('role')}）："
            f"一根筋={item.get('one_track')}；反差={item.get('contrast')}；"
            f"招牌={item.get('signature')}；外形锁定={item.get('look')}"
        )
    return "\n".join(lines)


def build_episode_messages(
    skill: str,
    plan: Dict[str, Any],
    episodes: Sequence[Dict[str, Any]],
    previous_tail: str,
) -> List[Dict[str, str]]:
    stage_note = (
        "【当前阶段：逐集正文】\n"
        "只写本次指定的这几集，严格按【五、格式手册】的对照样稿排版：\n"
        "集号行写 Episode X；场景头五段；正文只有 △ 画面、角色名台词、"
        "角色名 (V.O.)、[SFX] 四种积木；台词不加粗；不写 Props 行、Cast 行、"
        "集标题；每集至少 4 场；词数按本集分量落在 280~560 个英文词；"
        "每集最多一处 V.O.；集尾单独一行 — END OF EPISODE X —。\n"
        "全部用英文写。每集之间空一行。不要输出任何解释。"
    )
    target_lines = []
    for item in episodes:
        scenes = "；".join(str(scene) for scene in item.get("scenes", []))
        target_lines.append(
            f"Episode {item.get('number')}：事件={item.get('event', '')}；"
            f"情绪={item.get('emotion', '')}；场次安排={scenes}；"
            f"结尾钩子={item.get('hook', '')}"
        )
    user = (
        f"剧名：{plan.get('title_en')}\n"
        f"全剧大钩子：{plan.get('logline')}\n\n"
        f"【情节类别】\n{json.dumps(plan.get('categories', {}), ensure_ascii=False)}\n\n"
        f"【人物卡要点】\n{_characters_digest(plan)}\n\n"
        f"【全剧分集大纲】\n{_compact_outline(plan)}\n\n"
        f"【上一批结尾】\n{previous_tail or '（这是第一批，从第 1 集开头写起）'}\n\n"
        f"【本次要写的集】\n" + "\n".join(target_lines) + "\n\n"
        "现在开始写。从 Episode 开始，写到最后一集的 END OF EPISODE 为止。"
    )
    return [
        {"role": "system", "content": _system(skill, stage_note)},
        {"role": "user", "content": user},
    ]


def build_rating_messages(
    skill: str,
    plan: Dict[str, Any],
    episode_digest: str,
    excerpts: str,
) -> List[Dict[str, str]]:
    stage_note = (
        "【当前阶段：品质评级】\n"
        "按第⑦步的七项百分制和封顶规则给全剧评级。每项必须带集号依据，"
        "七项不许全给满分。严格按下面的 JSON 结构输出：\n"
        f"{RATING_SCHEMA}"
    )
    user = (
        f"【全剧分集大纲】\n{_compact_outline(plan)}\n\n"
        f"【逐集结尾钩子】\n{episode_digest}\n\n"
        f"【正文摘录】\n{excerpts}\n\n"
        "请完成品质评级。"
    )
    return [
        {"role": "system", "content": _system(skill, stage_note)},
        {"role": "user", "content": user},
    ]
